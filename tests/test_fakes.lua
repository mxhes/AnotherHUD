-- Tests for the client fakes in tests/fakes.lua.
local h = ...
local fakes = dofile("tests/fakes.lua")

h.test("secret value throws on arithmetic", function()
  local s = fakes.secret(5)
  h.eq(pcall(function() return s + 1 end), false)
  h.eq(pcall(function() return 1 - s end), false)
  h.eq(pcall(function() return s * 2 end), false)
  h.eq(pcall(function() return s / 2 end), false)
  h.eq(pcall(function() return s % 2 end), false)
  h.eq(pcall(function() return -s end), false)
end)

h.test("secret value throws on compare and concat", function()
  local s, t = fakes.secret(5), fakes.secret(6)
  h.eq(pcall(function() return s < 10 end), false)
  h.eq(pcall(function() return s <= 10 end), false)
  h.eq(pcall(function() return 10 < s end), false)
  h.eq(pcall(function() return s == t end), false)
  h.eq(pcall(function() return s .. "x" end), false)
  h.eq(fakes.isSecret(s), true)
  h.eq(fakes.isSecret(5), false)
end)

h.test("fake statusbar accepts secret", function()
  local client = fakes.client{}
  local bar = CreateFrame("StatusBar", "TestBar", UIParent)
  local s = fakes.secret(42)
  bar:SetValue(s)
  h.eq(rawequal(bar:GetValue(), s), true)
  local fs = bar:CreateFontString()
  fs:SetFont("font", 10, "")
  fs:SetText(s)
  h.eq(rawequal(fs:GetText(), s), true)
  h.eq(issecretvalue(bar:GetValue()), true)
  client.restore()
end)

h.test("a fake font string needs a font before its text", function()
  local f = fakes.frame("F")
  local fs = f:CreateFontString(nil, "OVERLAY")
  local ok, err = pcall(fs.SetText, fs, "x")
  h.eq(ok, false)
  h.eq(tostring(err):find("Font not set", 1, true) ~= nil, true, tostring(err))
  h.eq(pcall(fs.SetFormattedText, fs, "%s", "x"), false)
  fs:SetFont("font", 10, "OUTLINE")
  fs:SetText("x")
  h.eq(fs:GetText(), "x")
  local templated = f:CreateFontString(nil, "OVERLAY", "GameFontNormal")
  templated:SetText("y")
  h.eq(templated:GetText(), "y")
  local plain = f:CreateTexture()
  plain:SetText("z") -- not a font string: no check
end)

h.test("frame records calls and answers unset fields with no-ops", function()
  local f = fakes.frame("F")
  f:SetPoint("CENTER", 0, 0)
  f:Show()
  f:Hide()
  f:SetParent(nil)
  f:SomethingUnknown(1, 2)
  h.eq(#f.calls, 4)
  h.eq(f.calls[1][1], "SetPoint")
  h.eq(f.calls[1][2], "CENTER")
  h.eq(f.calls[4][1], "SetParent")
  h.eq(f:IsShown(), false)
end)

h.test("fire reaches registered handlers", function()
  local client = fakes.client{}
  local got = {}
  local a = CreateFrame("Frame")
  a:RegisterEvent("PLAYER_LOGIN")
  a:SetScript("OnEvent", function(_, event, x) got[#got + 1] = event .. ":" .. tostring(x) end)
  local b = CreateFrame("Frame")
  b:SetScript("OnEvent", function() got[#got + 1] = "unregistered" end)
  client.fire("PLAYER_LOGIN", 7)
  client.fire("OTHER_EVENT")
  h.eq(got, { "PLAYER_LOGIN:7" })
  client.restore()
end)

h.test("client combat, hooks, timer and restore", function()
  local client = fakes.client{ inCombat = true }
  h.eq(InCombatLockdown(), true)
  client.setCombat(false)
  h.eq(InCombatLockdown(), false)
  local ran = 0
  C_Timer.After(1, function() ran = ran + 1 end)
  h.eq(ran, 1) -- runs immediately
  local target = { Do = function(_, v) return v end }
  local seen
  hooksecurefunc(target, "Do", function(_, v) seen = v end)
  h.eq(target:Do(3), 3)
  h.eq(seen, 3)
  client.restore()
  h.eq(CreateFrame, nil)
  h.eq(InCombatLockdown, nil)
  h.eq(issecretvalue, nil)
end)

h.test("secret values throw on < and <=", function()
  local s = fakes.secret(1)
  h.eq(pcall(function() return s < 2 end), false)
  h.eq(pcall(function() return s <= 2 end), false)
  h.eq(pcall(function() return 2 < s end), false)
end)

h.test("withGlobals restores after an error", function()
  _G.FOO = 1
  _G.BAR = nil
  local ok = pcall(fakes.withGlobals, { FOO = 2, BAR = 3 }, function()
    h.eq(FOO, 2)
    h.eq(BAR, 3)
    error("x")
  end)
  h.eq(ok, false)
  h.eq(FOO, 1)
  h.eq(BAR, nil)
  fakes.withGlobals({ FOO = fakes.NIL }, function() h.eq(FOO, nil) end)
  h.eq(FOO, 1)
  _G.FOO = nil
end)

h.test("units answers secrets untouched", function()
  local hp = fakes.secret(5)
  local u = fakes.units{ target = { exists = true, health = hp, healthPct = fakes.secret(50), name = "Bob",
    casting = { name = "Bolt", texture = 1, notInterruptible = false, duration = "d" } } }
  local ok, err = pcall(function()
    h.eq(fakes.isSecret(UnitHealth("target")), true)
    h.eq(rawequal(UnitHealth("target"), hp), true)
    h.eq(fakes.isSecret(UnitHealthPercent("target")), true)
    h.eq(UnitExists("target"), true)
    h.eq(UnitExists("focus"), false)
    h.eq(UnitName("target"), "Bob")
    h.eq(UnitCastingInfo("target"), "Bolt")
    h.eq(UnitCastingInfo("focus"), nil)
    h.eq(UnitCastingDuration("target"), "d")
    h.eq(u.calls.UnitHealth, 2)
    u.set("target", "name", "Al")
    h.eq(UnitName("target"), "Al")
  end)
  u.restore()
  h.eq(UnitHealth, nil)
  if not ok then error(err, 0) end
end)

h.test("fake frames: formatted text, attributes, alpha, timer, sizes", function()
  local f = fakes.frame("F")
  local a, b = fakes.secret(1), fakes.secret(2)
  f:SetText("old")
  f:SetFormattedText("%s | %.0f%%", a, b)
  h.eq(f._fmt, "%s | %.0f%%")
  h.eq(rawequal(f._args[1], a), true)
  h.eq(rawequal(f._args[2], b), true)
  h.eq(f._text, nil)
  f:SetAttribute("unit", "target")
  h.eq(f:GetAttribute("unit"), "target")
  h.eq(f:GetAlpha(), 1)
  f:SetAlpha(0.5)
  h.eq(f:GetAlpha(), 0.5)
  f:SetAlphaFromBoolean(true, 1, 0.3)
  h.eq(f._alphaFrom, { true, 1, 0.3 })
  f:SetTimerDuration("d", 1, 2)
  h.eq(f._timer, { "d", 1, 2 })
  local order = {}
  f:SetScript("OnEvent", function() order[#order + 1] = "a" end)
  f:HookScript("OnEvent", function() order[#order + 1] = "b" end)
  f._scripts.OnEvent(f)
  h.eq(order, { "a", "b" })
  f:RegisterUnitEvent("UNIT_HEALTH", "player")
  h.eq(f._events.UNIT_HEALTH, true)
  f:SetSize(10, 20)
  h.eq({ f:GetWidth(), f:GetHeight() }, { 10, 20 })
  f:SetWidth(5)
  f:SetHeight(6)
  h.eq({ f._width, f._height }, { 5, 6 })
end)

h.test("client records state drivers", function()
  local client = fakes.client{}
  local f = fakes.frame("F")
  RegisterStateDriver(f, "visibility", "[combat] show; hide")
  h.eq(client.drivers[f], { attr = "visibility", cond = "[combat] show; hide" })
  UnregisterStateDriver(f, "visibility")
  h.eq(client.drivers[f], nil)
  client.restore()
end)
