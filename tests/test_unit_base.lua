h.test("reserveBelow pushes the cast bar under the resource bar", function()
  withUnits({}, {}, function(ns)
    local frame = make(ns, define(ns, "player"), "player")
    h.eq(frame.reserved, 0)
    h.eq(lastPoint(frame.cast.frame), { "SetPoint", "TOPLEFT", frame, "BOTTOMLEFT", 0, -14 })
    ns.Units.Base.reserveBelow(frame, 26)
    h.eq(frame.reserved, 26)
    h.eq(lastPoint(frame.cast.frame), { "SetPoint", "TOPLEFT", frame, "BOTTOMLEFT", 0, -26 })
    ns.Units.Base.reserveBelow(frame, 0)
    h.eq(lastPoint(frame.cast.frame), { "SetPoint", "TOPLEFT", frame, "BOTTOMLEFT", 0, -14 })
    ns.Units.Base.reserveBelow(frame, nil)
    h.eq(frame.reserved, 0)
  end)
end)

