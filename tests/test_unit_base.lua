-- Group members (Plan 4): Base.create with member = true; the caller keeps
-- the frames and lays them out with applyFrame.
local function member(ns, spec, o)
  o.member = true
  o.unit = o.unit or "party1"
  o.key = o.key or (spec.id .. ":1")
  local frame = ns.Units.Base.create(spec, o)
  ns.Units.Base.applyFrame(frame)
  return frame
end

local function lastPoint(f)
  local p
  for _, c in ipairs(f.calls) do if c[1] == "SetPoint" then p = c end end
  return p
end

