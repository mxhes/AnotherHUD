h.test("sample member shows its state", function()
  withUnits({}, {}, function(ns)
    local s = { name = "Torvald", class = "HUNTER", role = "DAMAGER", leader = true, dead = true,
      far = true, dispel = "Magic", healthPct = 0 }
    local frame = member(ns, define(ns, "party"), { role = true, dispel = true, range = true,
      sample = function() return s end })
    ns.Units.Base.editModeFrame(frame, true)
    h.eq(frame.bars.name:GetText(), "Torvald")
    h.near(frame:GetAlpha(), 0.55) -- far
    h.eq(frame.bars.healthRGB, { 0.35, 0.35, 0.35 }, "dead grey")
    h.eq(frame.bars.healthText._args, { ns.L["Dead"] }, "Dead text")
    h.eq(frame.bars.power._value, 0, "empty power")
    h.eq(frame.role.glyphFile, ns.Theme.textures.role.DAMAGER, "role badge")
    h.eq(frame.role.badge:IsShown(), true)
    h.eq(frame.role.crown:IsShown(), true, "crown")
    h.eq(frame.dispel.sampleTex:IsShown(), true, "dispel sample")
    h.eq(frame.dispel.sampleTex._color, ns.Theme.unitColors.debuff.Magic)
    s = { name = "Arthelis", class = "PALADIN", role = "TANK", healthPct = 84 }
    ns.Units.Base.applyFrame(frame)
    h.eq(frame.bars.health._value, 84, "healthPct as the bar value")
    h.eq(frame.bars.healthRGB, { 1, 1, 1 }, "class color")
    h.eq(frame:GetAlpha(), 1, "near")
    h.eq(frame.role.crown:IsShown(), false, "no crown")
    h.eq(frame.dispel.sampleTex:IsShown(), false, "no dispel")
    ns.Units.Base.editModeFrame(frame, false)
    h.eq(frame.dispel.sampleTex:IsShown(), false)
    h.eq(frame.role.badge:IsShown(), false, "no unit: badge gone")
  end)
end)

