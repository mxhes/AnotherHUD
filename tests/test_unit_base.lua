h.test("reserveBelow moves auras when the cast bar is off", function()
  withUnits({}, {}, function(ns)
    local frame = make(ns, define(ns, "player", { castBar = false }), "player")
    h.eq(lastPoint(frame.auras.frame), { "SetPoint", "TOPLEFT", frame, "BOTTOMLEFT", 0, -14 })
    ns.Units.Base.reserveBelow(frame, 26)
    h.eq(lastPoint(frame.auras.frame), { "SetPoint", "TOPLEFT", frame, "BOTTOMLEFT", 0, -26 })
    ns.Units.Base.reserveBelow(frame, 0)
    h.eq(lastPoint(frame.auras.frame), { "SetPoint", "TOPLEFT", frame, "BOTTOMLEFT", 0, -14 })
  end)
end)

h.test("reserveBelow waits for combat to end", function()
  withUnits({}, {}, function(ns, client)
    local frame = make(ns, define(ns, "player"), "player")
    client.setCombat(true)
    local before = count(frame.cast.frame, "SetPoint")
    ns.Units.Base.reserveBelow(frame, 26)
    h.eq(count(frame.cast.frame, "SetPoint"), before, "nothing in combat")
    client.setCombat(false)
    client.fire("PLAYER_REGEN_ENABLED")
    h.eq(lastPoint(frame.cast.frame), { "SetPoint", "TOPLEFT", frame, "BOTTOMLEFT", 0, -26 })
  end)
end)

